Student_marks = int(input("Enter your marks please: "))

if Student_marks <= 40:
    print(f"Ohh Sorry! Your score is = {Student_marks}.\nYou get the R grade")

elif Student_marks <= 50:
    print(f"Ohh your score is {Student_marks}.\nYou get the D grade")

elif Student_marks <= 60:
    print(f"Ohh your score is {Student_marks}.\nYou get the C grade")

elif Student_marks <= 70:
    print(f"Ohh your score is {Student_marks}.\nYou get the B grade")

elif Student_marks <= 80:
    print(f"Ohh your score is {Student_marks}.\nYou get the A grade")

else:
    print(f"Wow! your score is {Student_marks}.\nYou get the A+ grade")
